                        <h3>Fire Damage Prevention</h3>
                        <p>Once the fire has been put out and the Fire Damage Repairs have been performed, it is time to start thinking about prevention in the future. Here are some simple tips that can be used to stop more fires or at least limit the amount of damage they do. </p>
                        <h3>Fire Extinguishers</h3>
                        <p>Installing fire extinguishers in your home can help to fight the fire before help arrives and this can also help to reduce the damage caused by the fire.</p>
                        <h3>Sprinkler System</h3>
                        <p>Installing <a href="https://www.fireline.com/benefits-of-a-residential-sprinkler-system/" class="cddesclink" target="_blank">fire sprinklers</a> in your home can help to reduce the destruction due to a fire by around 90%, which can in turn help to reduce your insurance premiums. Sprinklers help to prevent the spreading of fire to other parts of your home by spraying water on the fire. Also, sprinklers use lesser water, almost 8.5 times lesser than traditional fire hoses while putting out a fire. Unfortunately this is very difficult unless the property is new construction.</p>
                        <h3>Smoke Detectors</h3>
                        <p>These are extremely useful and trigger an alarm to alert people in case of a fire outbreak. There are 2 types of <a href="https://www.allstate.com/tr.aspx" class="cddesclink" target="_blank">smoke detectors</a> – ionization smoke detectors and photoelectric smoke detectors. There are also smoke detectors that can be part of a SMART home and notify you via a mobile app even when you are not at home. </p>
                        <h3>No Open Flames</h3>
                        <p>Limit or eliminate the amount of open flames you have in your home or business. This includes candles, cigaretts, matches, lighters, etc. If you don’t use fire in your house, it drastically reduces your chance of getting fire damage! </p>
                        <h3>Final Tips for Fire Damage Restoration</h3>
                        <p>When a fire occurs, the period between 24-48 hours after the fire is known as the “golden hours” within which fire damage restoration can be done. This is the ideal period to start the fire damage restoration process. Here are some tips to get you started:</p>
                        <ul class="listing">
                            <li>Do NOT enter the home until it has been deemed safe and structurally sound by a qualified professional.</li>
                            <li>Beginning the damage recovery process early can help to prevent the costs of restoration from rising due to stains forming on furnishings, carpets and other materials.</li>
                            <li>However, it is not advisable to start the restoration process until 24 hours after the fire, as during this period all the smoke and dust will settle, which can cause respiratory problems. </li>
                            <li>The process should also not be started until documentation by yourself, a representative of yourself and your insurance company, so this can often delay the process. </li>
                            <li>When returning to your home after a fire outbreak, it is advisable to wear masks to avoid breathing in the smoke and dust, which can be harmful.</li>
                            <li>Avoid attempting to clean the draperies, upholstery of the furniture, carpets and other fabrics, as this will only cause the soot to get smeared further and cause greater damage.  </li>
                        </ul>
